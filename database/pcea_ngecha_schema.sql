-- 4) Keep updated_at current on every update
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
DECLARE
    table_name TEXT;
    trigger_name TEXT;
    managed_tables TEXT[] := ARRAY[
        'users',
        'ministers',
        'districts',
        'elders',
        'deacons',
        'members',
        'church_groups',
        'group_officers',
        'sermons',
        'events',
        'announcements',
        'albums',
        'gallery',
        'donations',
        'prayer_requests',
        'newsletter_subscribers',
        'contact_messages'
    ];
BEGIN
    FOREACH table_name IN ARRAY managed_tables LOOP
        trigger_name := format('trg_%s_updated_at', table_name);

        IF EXISTS (
            SELECT 1
            FROM pg_trigger t
            JOIN pg_class c ON c.oid = t.tgrelid
            JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE t.tgname = trigger_name
              AND c.relname = table_name
              AND n.nspname = current_schema()
        ) THEN
            EXECUTE format('DROP TRIGGER %I ON %I', trigger_name, table_name);
        END IF;

        EXECUTE format(
            'CREATE TRIGGER %I BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION set_updated_at()',
            trigger_name,
            table_name
        );
    END LOOP;
END;
$$;

